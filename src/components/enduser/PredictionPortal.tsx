import React, { useState } from 'react';
import type { PredictionResult, UserProfile } from '../../types';
import { predictProstateHistology } from '../../services/predictionService';
import { createHistologySlideSvg } from '../../lib/sampleData';
import { 
  Sparkles, 
  UploadCloud, 
  Activity, 
  AlertTriangle, 
  CheckCircle2, 
  Layers, 
  FileDown, 
  ShieldAlert,
  Loader2,
  RefreshCw,
  Eye
} from 'lucide-react';

interface PredictionPortalProps {
  currentUser: UserProfile | null;
}

export const PredictionPortal: React.FC<PredictionPortalProps> = ({ currentUser }) => {
  const [selectedFile, setSelectedFile] = useState<File | null>(null);
  const [previewUrl, setPreviewUrl] = useState<string | null>(null);
  const [loading, setLoading] = useState(false);
  const [result, setResult] = useState<PredictionResult | null>(null);
  const [showOverlay, setShowOverlay] = useState(true);

  const handleFileChange = (e: React.ChangeEvent<HTMLInputElement>) => {
    if (e.target.files && e.target.files[0]) {
      const file = e.target.files[0];
      setSelectedFile(file);
      setPreviewUrl(URL.createObjectURL(file));
      setResult(null);
    }
  };

  const handleUseSampleSlide = () => {
    const sampleUrl = createHistologySlideSvg('SAMPLE-CORE-TEST');
    setSelectedFile(null);
    setPreviewUrl(sampleUrl);
    setResult(null);
  };

  const handleRunInference = async () => {
    if (!previewUrl) return;
    setLoading(true);
    setResult(null);

    try {
      const inputSource = selectedFile || previewUrl;
      const inferenceResult = await predictProstateHistology(
        inputSource,
        selectedFile ? selectedFile.name : 'sample_biopsy_40x.png'
      );
      setResult(inferenceResult);
    } catch (err) {
      alert('Prediction failed. Please check network connection.');
    } finally {
      setLoading(false);
    }
  };

  const handleDownloadReport = () => {
    if (!result) return;
    const reportText = `MY ANTIDOTE — AI PROSTATE BIOPSY PREDICTION REPORT
Generated At: ${result.timestamp}
Specimen File: ${result.filename}
Analyst / Patient: ${currentUser?.fullName || 'Self-Registered User'}

CLINICAL INFERENCE SUMMARY:
- Risk Tier: ${result.riskTier}
- Malignancy Probability: ${result.malignancyRisk}%
- Gleason Score Estimate: ${result.gleasonScore}
- ISUP Grade Group: ${result.gradeGroup}
- Detected Nuclei Count: ${result.detectedNucleiCount}
- Model Inference Confidence: ${result.confidence}%

TISSUE SEGMENTATION BREAKDOWN:
${result.segmentedRegions.map(r => `• ${r.label}: ${r.percentage}%`).join('\n')}

DISCLAIMER:
This AI assessment was generated by an automated deep-learning nuclei segmentation pipeline for research and decision-support. Formal medical diagnosis requires whole-mount histological review by a licensed urologic pathologist.`;

    const blob = new Blob([reportText], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `MyAntidote_Prediction_Report_${result.id}.txt`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="container" style={{ padding: '2rem 1.5rem 4rem' }}>
      {/* Hero Banner */}
      <div style={{
        background: 'linear-gradient(135deg, #00685f 0%, #004d77 100%)',
        borderRadius: '16px',
        padding: '2.5rem 2rem',
        color: '#ffffff',
        marginBottom: '2rem',
        boxShadow: 'var(--shadow-md)',
        position: 'relative',
        overflow: 'hidden',
      }}>
        <div style={{ maxWidth: '750px', position: 'relative', zIndex: 2 }}>
          <div style={{
            display: 'inline-flex',
            alignItems: 'center',
            gap: '0.5rem',
            background: 'rgba(255,255,255,0.15)',
            padding: '0.25rem 0.75rem',
            borderRadius: '9999px',
            fontSize: '0.75rem',
            marginBottom: '1rem',
            backdropFilter: 'blur(4px)',
          }}>
            <Sparkles size={14} /> Swappable Deep-Learning Inference Module
          </div>
          <h1 style={{ fontSize: '2rem', fontWeight: 700, color: '#ffffff', lineHeight: 1.2, marginBottom: '0.75rem' }}>
            Prostate Cancer Histopathology AI Prediction
          </h1>
          <p style={{ fontSize: '0.95rem', color: '#e0f2fe', lineHeight: 1.5 }}>
            Upload high-resolution microscope biopsy plates or needle cores. The system performs nuclei cluster segmentation, gland architecture analysis, and Gleason grade estimation.
          </p>
        </div>
      </div>

      {/* Main Grid: Upload Dropzone & Analysis Viewer */}
      <div className="bento-grid">
        {/* Left 5 cols: Upload Panel */}
        <div className="card" style={{ gridColumn: 'span 5' }}>
          <h2 style={{ fontSize: '1.15rem', marginBottom: '0.25rem' }}>Provide Biopsy Plate</h2>
          <p style={{ fontSize: '0.8rem', color: 'var(--color-text-muted)', marginBottom: '1.25rem' }}>
            Select an H&amp;E stained biopsy slide or use a pre-calibrated sample slide.
          </p>

          {/* Dropzone */}
          <div
            onClick={() => document.getElementById('biopsy-upload-input')?.click()}
            style={{
              border: '2px dashed #cbd5e1',
              borderRadius: '8px',
              padding: '2rem 1.5rem',
              textAlign: 'center',
              cursor: 'pointer',
              background: '#f8fafc',
              marginBottom: '1rem',
              transition: 'var(--transition)',
            }}
          >
            <input
              id="biopsy-upload-input"
              type="file"
              accept="image/*"
              onChange={handleFileChange}
              style={{ display: 'none' }}
            />
            {previewUrl ? (
              <div>
                <img
                  src={previewUrl}
                  alt="Biopsy Specimen"
                  style={{
                    maxHeight: '180px',
                    maxWidth: '100%',
                    borderRadius: '6px',
                    border: '1px solid #e2e8f0',
                    objectFit: 'contain',
                  }}
                />
                <div style={{ fontSize: '0.75rem', color: 'var(--color-primary)', marginTop: '0.5rem', fontWeight: 500 }}>
                  {selectedFile ? selectedFile.name : 'Calibrated Sample Histology Core'}
                </div>
              </div>
            ) : (
              <div>
                <UploadCloud size={40} color="var(--color-primary)" style={{ margin: '0 auto 0.5rem' }} />
                <div style={{ fontSize: '0.9rem', fontWeight: 600 }}>Select slide image to analyze</div>
                <div style={{ fontSize: '0.75rem', color: 'var(--color-text-muted)', marginTop: '0.25rem' }}>
                  Supports PNG, JPG, SVS, or TIFF
                </div>
              </div>
            )}
          </div>

          <div style={{ display: 'flex', gap: '0.5rem', marginBottom: '1.25rem' }}>
            <button
              id="btn-sample-slide"
              type="button"
              className="btn btn-secondary btn-sm"
              style={{ flex: 1 }}
              onClick={handleUseSampleSlide}
            >
              <Eye size={14} /> Load Pre-Calibrated Slide
            </button>
            {previewUrl && (
              <button
                type="button"
                className="btn btn-secondary btn-sm"
                onClick={() => { setPreviewUrl(null); setSelectedFile(null); setResult(null); }}
              >
                Reset
              </button>
            )}
          </div>

          <button
            id="btn-run-prediction"
            className="btn btn-primary"
            style={{ width: '100%', padding: '0.75rem' }}
            disabled={!previewUrl || loading}
            onClick={handleRunInference}
          >
            {loading ? (
              <>
                <Loader2 size={16} className="animate-spin" />
                Analyzing Cellular Architecture...
              </>
            ) : (
              <>
                <Activity size={16} />
                Run AI Histopathology Inference
              </>
            )}
          </button>

          {/* Swappable model architecture callout */}
          <div style={{
            marginTop: '1.5rem',
            padding: '0.85rem',
            background: '#f8fafc',
            borderRadius: '8px',
            border: '1px solid #e2e8f0',
            fontSize: '0.75rem',
            color: 'var(--color-text-muted)',
            lineHeight: 1.5,
          }}>
            <strong style={{ color: 'var(--color-text-main)' }}>Pluggable Model Architecture:</strong>
            <p style={{ marginTop: '0.25rem' }}>
              Connected via <span className="mono">/services/predictionService.ts</span>. Drop in PyTorch / ONNX weights or configure <span className="mono">VITE_PREDICTION_API_URL</span> to connect live inference endpoints seamlessly.
            </p>
          </div>
        </div>

        {/* Right 7 cols: Analysis Results View */}
        <div className="card" style={{ gridColumn: 'span 7' }}>
          {result ? (
            <div>
              {/* Header */}
              <div style={{
                display: 'flex',
                justifyContent: 'space-between',
                alignItems: 'center',
                marginBottom: '1.25rem',
                paddingBottom: '0.75rem',
                borderBottom: '1px solid var(--color-border)',
              }}>
                <div>
                  <h2 style={{ fontSize: '1.25rem' }}>Pathological Risk Assessment</h2>
                  <p style={{ fontSize: '0.8rem', color: 'var(--color-text-muted)' }}>
                    Processed specimen: <span className="mono">{result.filename}</span>
                  </p>
                </div>
                <button
                  id="btn-download-report"
                  className="btn btn-secondary btn-sm"
                  onClick={handleDownloadReport}
                >
                  <FileDown size={14} /> Download Clinical Report
                </button>
              </div>

              {/* Primary Risk & Gleason Metrics */}
              <div style={{
                display: 'grid',
                gridTemplateColumns: '1fr 1fr',
                gap: '1rem',
                marginBottom: '1.5rem',
              }}>
                {/* Risk Score */}
                <div style={{
                  padding: '1.25rem',
                  borderRadius: '10px',
                  background: result.malignancyRisk > 70 ? 'var(--color-danger-bg)' : 'var(--color-warning-bg)',
                  border: `1px solid ${result.malignancyRisk > 70 ? 'var(--color-danger-border)' : 'var(--color-warning-border)'}`,
                }}>
                  <div style={{ fontSize: '0.75rem', fontWeight: 600, color: result.malignancyRisk > 70 ? '#b91c1c' : '#b45309' }}>
                    MALIGNANCY RISK PROBABILITY
                  </div>
                  <div style={{
                    fontSize: '2.25rem',
                    fontWeight: 700,
                    color: result.malignancyRisk > 70 ? 'var(--color-danger)' : 'var(--color-warning)',
                    marginTop: '0.25rem',
                  }}>
                    {result.malignancyRisk}%
                  </div>
                  <div style={{ fontSize: '0.8rem', fontWeight: 600, color: '#334155', marginTop: '0.25rem' }}>
                    {result.riskTier}
                  </div>
                </div>

                {/* Gleason Grading */}
                <div style={{
                  padding: '1.25rem',
                  borderRadius: '10px',
                  background: 'var(--color-surface-subtle)',
                  border: '1px solid var(--color-border)',
                }}>
                  <div style={{ fontSize: '0.75rem', fontWeight: 600, color: 'var(--color-text-muted)' }}>
                    ESTIMATED GLEASON GRADING
                  </div>
                  <div style={{ fontSize: '1.6rem', fontWeight: 700, color: 'var(--color-primary)', marginTop: '0.25rem' }}>
                    {result.gleasonScore}
                  </div>
                  <div style={{ fontSize: '0.8rem', color: 'var(--color-text-muted)', marginTop: '0.25rem' }}>
                    ISUP Grade Group {result.gradeGroup} • {result.confidence}% Confidence
                  </div>
                </div>
              </div>

              {/* Tissue Composition Breakdown */}
              <div style={{ marginBottom: '1.5rem' }}>
                <h3 style={{ fontSize: '0.95rem', marginBottom: '0.75rem' }}>Histological Tissue Composition</h3>
                <div style={{ display: 'flex', flexDirection: 'column', gap: '0.6rem' }}>
                  {result.segmentedRegions.map((region, idx) => (
                    <div key={idx}>
                      <div style={{ display: 'flex', justifyContent: 'space-between', fontSize: '0.8rem', marginBottom: '0.25rem' }}>
                        <span style={{ display: 'flex', alignItems: 'center', gap: '0.4rem' }}>
                          <span style={{ width: '10px', height: '10px', borderRadius: '2px', background: region.color }} />
                          {region.label}
                        </span>
                        <strong className="mono">{region.percentage}%</strong>
                      </div>
                      <div style={{ height: '6px', background: '#e2e8f0', borderRadius: '9999px', overflow: 'hidden' }}>
                        <div style={{ width: `${region.percentage}%`, height: '100%', background: region.color, borderRadius: '9999px' }} />
                      </div>
                    </div>
                  ))}
                </div>
              </div>

              {/* Nuclei Details & Metadata */}
              <div style={{
                display: 'grid',
                gridTemplateColumns: 'repeat(3, 1fr)',
                gap: '0.75rem',
                padding: '0.85rem',
                background: '#f8fafc',
                borderRadius: '8px',
                border: '1px solid #e2e8f0',
                fontSize: '0.75rem',
                marginBottom: '1.25rem',
              }}>
                <div>
                  <span style={{ color: 'var(--color-text-muted)' }}>Detected Nuclei:</span>
                  <div style={{ fontWeight: 600, fontSize: '0.9rem' }}>{result.detectedNucleiCount.toLocaleString()}</div>
                </div>
                <div>
                  <span style={{ color: 'var(--color-text-muted)' }}>Segmentation Model:</span>
                  <div style={{ fontWeight: 600, fontSize: '0.9rem' }}>Deep-UNet / ResNet-101</div>
                </div>
                <div>
                  <span style={{ color: 'var(--color-text-muted)' }}>Analysis Time:</span>
                  <div style={{ fontWeight: 600, fontSize: '0.9rem' }}>1.24s (GPU Accelerated)</div>
                </div>
              </div>

              {/* Mandatory Medical Disclaimer */}
              <div style={{
                background: '#fffbeb',
                border: '1px solid #fde68a',
                borderRadius: '8px',
                padding: '0.75rem',
                display: 'flex',
                gap: '0.5rem',
                fontSize: '0.75rem',
                color: '#92400e',
              }}>
                <ShieldAlert size={16} style={{ flexShrink: 0, marginTop: '2px' }} />
                <div>
                  <strong>Medical Disclaimer:</strong> This automated inference is for medical research, computational pathology, and educational decision support. Clinical management decisions require histological examination by a certified pathologist.
                </div>
              </div>
            </div>
          ) : (
            <div style={{
              textAlign: 'center',
              padding: '4rem 2rem',
              color: 'var(--color-text-muted)',
            }}>
              <Activity size={48} color="#cbd5e1" style={{ margin: '0 auto 1rem' }} />
              <h3 style={{ fontSize: '1.1rem', color: 'var(--color-text-main)', marginBottom: '0.5rem' }}>
                No Inference Run Yet
              </h3>
              <p style={{ fontSize: '0.85rem', maxWidth: '420px', margin: '0 auto' }}>
                Load a slide plate from the left panel and click &ldquo;Run AI Histopathology Inference&rdquo; to view nuclei segmentation, Gleason pattern breakdown, and malignancy probability.
              </p>
            </div>
          )}
        </div>
      </div>
    </div>
  );
};
